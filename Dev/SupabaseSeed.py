import argparse
import json
import sqlite3
from contextlib import closing
from pathlib import Path

from server.DeploymentData import SEED_ACCESS, SEED_SOURCES
from server.FacilityImport import PROJECT, parse_facilities, read_access
from server.Models import AccessPoint, Facility


def public_rows() -> tuple[list[tuple], list[tuple]]:
    resources = PROJECT.parent / "Resource"
    facilities = []
    for file, label, hold in SEED_SOURCES:
        rows, _ = parse_facilities(resources / file, label, hold_ids={hold})
        facilities.extend((f.id, f.coordinates.lat, f.coordinates.lng, f.model_dump_json()) for f in rows)
    access, skipped = read_access(resources / SEED_ACCESS)
    if len(facilities) != 91 or len(access) != 10 or skipped:
        raise ValueError("초기 배포 데이터 건수가 예상과 다릅니다.")
    return facilities, access


def sqlite_rows(path: Path) -> tuple[list[tuple], list[tuple]]:
    with closing(sqlite3.connect(path.resolve().as_uri() + "?mode=ro", uri=True)) as db, db:
        db.execute("BEGIN")
        facilities = db.execute("SELECT id, lat, lng, payload FROM facilities").fetchall()
        access = db.execute("SELECT kind, facility_id, name, mode, lat, lng, payload FROM access").fetchall()
    for facility_id, lat, lng, payload in facilities:
        facility = Facility.model_validate_json(payload)
        if (facility.id, facility.coordinates.lat, facility.coordinates.lng) != (facility_id, lat, lng):
            raise ValueError("시설 ID 또는 좌표가 저장된 데이터와 일치하지 않습니다.")
    for *_, lat, lng, payload in access:
        point = AccessPoint.model_validate_json(payload)
        if (point.coordinates.lat, point.coordinates.lng) != (lat, lng):
            raise ValueError("접근점 좌표가 저장된 데이터와 일치하지 않습니다.")
    return facilities, access


def sql_text(value: str) -> str:
    return "E'" + value.replace("\\", "\\\\").replace("'", "''") + "'"


def insert(table: str, columns: str, rows: list[tuple], key: str, *, update: bool) -> str:
    if not rows:
        return ""
    values = []
    for *fields, payload in sorted(rows):
        parts = [sql_text(value) if isinstance(value, str) else repr(value) for value in fields]
        parts.append(sql_text(json.dumps(json.loads(payload), ensure_ascii=False, separators=(",", ":"))) + "::jsonb")
        values.append("  (" + ", ".join(parts) + ")")
    if update:
        coordinates = "lat = excluded.lat, lng = excluded.lng, " if table == "facilities" else ""
        on_conflict = f"({key}) do update set {coordinates}payload = excluded.payload"
    else:
        on_conflict = "do nothing"
    return f"insert into find_nearby.{table} ({columns}) values\n" + ",\n".join(values) + f"\non conflict {on_conflict};\n"


def main() -> None:
    parser = argparse.ArgumentParser(description="공공시설 데이터를 PostgreSQL 적재용 SQL로 내보냅니다.")
    parser.add_argument("output", type=Path)
    parser.add_argument("--sqlite", type=Path, help="지역 CSV 대신 기존 시설 SQLite를 읽습니다.")
    args = parser.parse_args()
    facilities, access = sqlite_rows(args.sqlite) if args.sqlite else public_rows()
    sql = [
        "-- Generated by SupabaseSeed.py from the verified public facility data.",
        insert("facilities", "id, lat, lng, payload", facilities, "id", update=bool(args.sqlite)),
        insert(
            "access_points", "kind, facility_id, name, mode, lat, lng, payload", access,
            "kind, facility_id, name, mode, lat, lng", update=bool(args.sqlite),
        ),
    ]
    args.output.write_text("\n".join(sql), encoding="utf-8", newline="\n")
    print(f"시설 {len(facilities)}곳, 접근점 {len(access)}건 SQL 생성")


if __name__ == "__main__":
    main()
